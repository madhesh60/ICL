"""`cairn bench`: every number that can be measured without a GPU, in one report.

Nothing here calls a language model.  The report answers:

    1. How broken is the official baseline's output?  (read from its own zip)
    2. What do "no model at all" methods score?        (floors to beat)
    3. Does coverage selection build a better prompt than file order or random?
    4. How much prompt reading does the cache layout save, and does scheduling matter?
    5. Can the code checker be trusted?                 (run on the dataset's own kernels)
    6. How fast is prompt building?

Every number is computed from the data files when the command runs, so the
report can be regenerated at any time and checked by anyone.
"""

from __future__ import annotations

import ast
import json
import time
import zipfile
from dataclasses import replace
from pathlib import Path

import numpy as np

from cairn.config import AppConfig
from cairn.context.builder import ContextBuilder, ContextConfig
from cairn.data import DEFAULT_DATA_DIR, load_task, split_examples
from cairn.decoding.calibrate import StackedCalibrator
from cairn.decoding.constraints import satisfies
from cairn.eval.baselines import knn_accuracy, majority_accuracy
from cairn.eval.contextbench import context_report, simulate_prefix_cache
from cairn.pipeline.signals import signal_row
from cairn.tasks import get_task
from cairn.tasks.kernel import parse_wrapper_signature, static_check
from cairn.tokens import TokenCounter

BASELINE_ZIP = DEFAULT_DATA_DIR.parent / "outputs" / "result.zip"


def _valid_answer(task_id: int, value: object, labels: tuple[str, ...]) -> bool:
    """Would this prediction even be a well-formed answer for the task?"""
    if value is None or not str(value).strip():
        return False
    text = str(value)
    spec = get_task(task_id, labels)
    if spec.kind == "classification":
        return text in spec.labels
    if task_id == 1:
        return text.lstrip("-").isdigit()
    if task_id == 3:
        return satisfies(spec.constraint, text)
    if task_id == 4:
        return " " not in text and len(text) < 200
    if task_id == 8:
        try:
            ast.parse(text)
        except SyntaxError:
            return False
        return "triton" in text
    return len(text) < 100  # trivia answers are short


def baseline_audit(data_dir: Path | None) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    if not BASELINE_ZIP.exists():
        return rows
    with zipfile.ZipFile(BASELINE_ZIP) as archive:
        for task_id in range(1, 9):
            name = next(n for n in archive.namelist() if n.startswith(f"openseek-{task_id}-"))
            lines = [
                json.loads(line)
                for line in archive.read(name).decode().splitlines()
                if line.strip()
            ]
            task = load_task(task_id, data_dir)
            labels = tuple(sorted({e.output for e in task.examples}))
            nulls = sum(1 for r in lines if r.get("prediction") is None)
            invalid = sum(
                1
                for r in lines
                if r.get("prediction") is not None
                and not _valid_answer(task_id, r["prediction"], labels)
            )
            rows.append(
                {
                    "task": task_id,
                    "n": len(lines),
                    "null": nulls,
                    "invalid": invalid,
                    "lost_share": (nulls + invalid) / max(len(lines), 1),
                }
            )
    return rows


def _builder(task_id, app, counter, data_dir, context=None, targets=None):
    task = load_task(task_id, data_dir)
    run_cfg = app.for_task(task_id)
    splits = split_examples(task.examples, run_cfg.splits, run_cfg.split_seed)
    spec = get_task(task_id, tuple(e.output for e in splits.pool))
    builder = ContextBuilder(
        spec,
        splits.pool,
        counter,
        context or run_cfg.context,
        definition=task.definition,
        target_inputs=targets,
    )
    return task, splits, builder


def run_bench(
    app: AppConfig, counter: TokenCounter, data_dir: Path | None, dev_limit: int = 300
) -> str:
    started = time.time()
    out: list[str] = [
        "# Offline benchmark report",
        "",
        "Generated by `cairn bench`. No language model was called: every number below comes",
        f"from the data files and plain arithmetic. Token counter: `{counter.name}`.",
        "",
    ]

    # 1 ---------------------------------------------------------------- baseline
    audit = baseline_audit(data_dir)
    if audit:
        out += [
            "## 1. The official baseline loses answers before accuracy is even measured",
            "",
            "Read from the organisers' own `outputs/result.zip`. *null* = no answer at all; "
            "*invalid* = text that cannot be a correct answer (wrong label, template words, "
            "not code). Those predictions are wrong no matter how smart the model is.",
            "",
            "| task | predictions | null | invalid | lost before scoring |",
            "|---|---|---|---|---|",
        ]
        for row in audit:
            out.append(
                f"| {row['task']} | {row['n']} | {row['null']} | {row['invalid']} | "
                f"{row['lost_share']:.0%} |"
            )
        total_lost = sum(r["null"] + r["invalid"] for r in audit)  # type: ignore[operator]
        total = sum(r["n"] for r in audit)  # type: ignore[misc]
        out += [
            "",
            f"Overall: **{total_lost / total:.0%}** of baseline predictions are lost to format.",
            "",
        ]

    # 2 --------------------------------------------------------------- floors
    out += [
        "## 2. Model-free floors (dev split, never seen in any prompt)",
        "",
        "*kNN vote* answers like the most similar labelled examples (BM25 word overlap). "
        "A model pipeline that does not beat this is not adding anything.",
        "",
        "| task | dev | majority label accuracy | kNN-15 vote accuracy |",
        "|---|---|---|---|",
    ]
    for task_id in range(1, 8):
        task, splits, builder = _builder(task_id, app, counter, data_dir)
        dev = splits.as_queries("dev")[:dev_limit]
        _, majority = majority_accuracy(splits.pool, dev)
        out.append(
            f"| {task_id} | {len(dev)} | {majority:.1%} | {knn_accuracy(builder, dev):.1%} |"
        )
    out.append("")

    # 3 ------------------------------------------------------ context designs
    out += [
        "## 3. Which examples fill the 30K tokens?",
        "",
        "Same token budget, four ways to choose. *coverage* = share of each dev input's "
        "informative words and word pairs (weighted by rarity) that appear somewhere in "
        "the shared example block. *streak* = longest run of one label in a row. "
        "*examples* = how many fit (cheaper examples = more variety in the same budget).",
        "",
        "| task | method | examples | coverage | label streak | min example tokens |",
        "|---|---|---|---|---|---|",
    ]
    designs = {
        "file order (baseline)": ContextConfig(selection="first", tail_k=0),
        "random": ContextConfig(selection="random", tail_k=0),
        "coverage of pool": ContextConfig(selection="coverage", coverage_target="pool", tail_k=0),
        "coverage of inputs (Cairn)": ContextConfig(
            selection="coverage", coverage_target="queries", tail_k=0
        ),
    }
    for task_id in (2, 5, 6, 7):
        task = load_task(task_id, data_dir)
        splits = split_examples(task.examples)
        dev = splits.as_queries("dev")[:dev_limit]
        for name, cfg in designs.items():
            _, _, builder = _builder(task_id, app, counter, data_dir, cfg, [q.input for q in dev])
            report = context_report(builder, dev)
            streak = report.longest_label_streak if builder.spec.kind == "classification" else "-"
            out.append(
                f"| {task_id} | {name} | {report.mean_bulk_examples:.0f} | {report.coverage:.3f} | "
                f"{streak} | {report.min_demo_tokens:,} |"
            )
    out.append("")

    # 4 -------------------------------------------------------------- caching
    out += [
        "## 4. Prompt reading saved by the cache-aligned layout",
        "",
        "200 dev prompts of task 7 replayed through a model of vLLM's prefix cache "
        "(16-token blocks, the server remembers 2 prompt beginnings). *to read* = prompt "
        "tokens the GPU must actually process. Without any reuse it would read all of them.",
        "",
        "| clusters | shared part | send order | coverage | cache share | tokens to read |",
        "|---|---|---|---|---|---|",
    ]
    task = load_task(7, data_dir)
    splits = split_examples(task.examples)
    dev = splits.as_queries("dev")[:200]
    for clusters, shared in ((1, 1.0), (4, 0.5), (8, 0.5), (8, 0.0)):
        cfg = replace(app.for_task(7).context, n_clusters=clusters, global_frac=shared)
        _, _, builder = _builder(7, app, counter, data_dir, cfg, [q.input for q in dev])
        coverage = context_report(builder, dev).coverage
        for grouped in (True, False):
            sim = simulate_prefix_cache(builder, dev, counter, grouped=grouped, slots=2)
            out.append(
                f"| {clusters} | {shared:.0%} | {'grouped (Cairn)' if grouped else 'arrival'} | "
                f"{coverage:.3f} | {sim.cache_share:.1%} | {sim.tokens_to_read / 1e6:.2f}M of "
                f"{sim.total_tokens / 1e6:.2f}M |"
            )
    out.append("")

    # 4b ------------------------------------------------------------- signals
    out += [
        "## 5. Cheap signals, combined by the stacked calibrator (still no model)",
        "",
        "A logistic regression fitted on the *calib* split, scored on *dev*. Inputs: the "
        "nearest-examples vote, plus task signals where the task card defines them. With a "
        "real model, the model's own label scores are added as further inputs.",
        "",
        "| task | majority | kNN vote | stacked: kNN vote + task signals |",
        "|---|---|---|---|",
    ]
    for task_id in (2, 5, 6):
        task, splits, builder = _builder(task_id, app, counter, data_dir)
        labels = builder.spec.labels
        index = {label: i for i, label in enumerate(labels)}
        calib, dev = list(splits.calib), splits.as_queries("dev")[:dev_limit]
        rows = np.vstack([signal_row(builder, e.input) for e in calib])
        k = len(labels)
        stack = StackedCalibrator().fit(rows[:, :k], [index[e.output] for e in calib], rows[:, k:])
        dev_rows = np.vstack([signal_row(builder, q.input) for q in dev])
        predicted = stack.transform(dev_rows[:, :k], dev_rows[:, k:]).argmax(axis=1)
        stacked = float(np.mean([labels[p] == q.gold for p, q in zip(predicted, dev, strict=True)]))
        _, majority = majority_accuracy(splits.pool, dev)
        out.append(
            f"| {task_id} | {majority:.1%} | {knn_accuracy(builder, dev):.1%} | **{stacked:.1%}** |"
        )
    out.append("")

    # 5 --------------------------------------------------------------- checker
    task8 = load_task(8, data_dir)
    flagged = [e for e in task8.examples if not static_check(e.output).ok]
    signatures = sum(parse_wrapper_signature(q.input) is not None for q in task8.test)
    out += [
        "## 6. Can the code checker be trusted?",
        "",
        "Run on the dataset's own reference kernels, which are known to be real code:",
        "",
        f"- Signatures parsed from test inputs: **{signatures}/{len(task8.test)}**",
        f"- Reference kernels passing the static check: **{len(task8.examples) - len(flagged)}"
        f"/{len(task8.examples)}**",
    ]
    for example in flagged:
        out.append(f"  - flagged: {static_check(example.output).problems[0]}")
    out.append("")

    # 6 ----------------------------------------------------------------- speed
    timings = []
    for task_id in (1, 6, 7):
        t0 = time.perf_counter()
        task, splits, builder = _builder(task_id, app, counter, data_dir)
        setup = time.perf_counter() - t0
        queries = list(task.test[:100])
        t1 = time.perf_counter()
        for q in queries:
            builder.build(q)
        per = (time.perf_counter() - t1) / len(queries) * 1000
        timings.append((task_id, setup, per))
    out += [
        "## 7. Prompt building speed (one CPU core)",
        "",
        "| task | one-time setup | per prompt |",
        "|---|---|---|",
        *[f"| {t} | {s:.1f}s | {p:.1f} ms |" for t, s, p in timings],
        "",
        f"_Report built in {time.time() - started:.0f}s._",
        "",
    ]
    return "\n".join(out)
